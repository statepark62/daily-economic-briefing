"""
수집된 데이터를 Claude API에 넘겨 분석 텍스트를 생성한다.
- mode="weekly": 주간 심층 브리핑 (긴 종합 분석)
- mode="daily": 조건부 일일 속보 (짧은 1~2문단)
"""

import os
import json
import anthropic

_api_key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
if not _api_key:
    raise RuntimeError(
        "ANTHROPIC_API_KEY 환경변수(secret)가 비어있습니다. "
        "저장소 Settings > Secrets and variables > Actions에서 값을 확인해주세요."
    )

client = anthropic.Anthropic(
    api_key=_api_key,
    timeout=60.0,      # 연결이 느릴 때 너무 빨리 포기하지 않도록
    max_retries=3,     # 일시적 연결 오류 시 자동 재시도
)

SYSTEM_PROMPT = """당신은 경제 데이터를 비전문가도 이해할 수 있게 쉽게 풀어서 설명하는 해설자입니다.
반드시 지켜야 할 규칙:
- 전문용어(예: 기준금리, 국채금리, 달러인덱스 등)가 나오면 처음 등장할 때 괄호로 짧게 뜻을 풀어준다.
- 숫자와 표보다 "그래서 이게 무슨 뜻인지"를 문장으로 풀어서 설명하는 데 중점을 둔다.
- "매수하라/매도하라/지금 사라/지금 팔아라/~하세요/~하지 마세요" 같은 명령형 지시 문장은 절대 쓰지 않는다.
- 대신 "~하는 쪽에 무게를 두는 게 합리적일 수 있습니다", "~서두르기보다는 지켜보는 접근이 있을 수 있습니다"처럼,
  단정적이지 않으면서도 뚜렷한 결론처럼 읽히는 문장으로 표현한다 (여러 선택지를 나열만 하지 말고, 지금 데이터가
  가리키는 쪽을 분명하게 짚어준다).
- 데이터가 비어있는 항목은 "데이터 없음"이라고 명시하고 추측하지 않는다.
- 마지막에 "본 내용은 투자 자문이 아니며, 참고용 정보이니 최종 판단과 책임은 본인에게 있습니다"라는
  문구를 반드시 포함한다.
- 한국어로, 친근하고 쉬운 말투로 작성한다.
"""


def generate_weekly_report(data: dict) -> str:
    prompt = f"""아래는 이번 주 수집된 경제 데이터입니다 (JSON):

{json.dumps(data, ensure_ascii=False, indent=2)}

다음 구성으로, 경제 지식이 많지 않은 일반인도 이해할 수 있는 쉬운 말로 주간 브리핑을 작성해주세요:

1. 금리 이야기 (미국/한국) — 무슨 일이 있었고, 그게 왜 중요한지
2. 환율 이야기 (원/달러, 달러인덱스) — 원화가 강해졌는지 약해졌는지, 그게 일상에 어떤 의미인지
3. 주요 지수 이야기 (코스피, S&P500) — 시장 분위기가 어땠는지
4. 이번 주 종합 정리 — 위 내용을 한 문단으로 쉽게 요약
5. 앞으로 대비 방향에 대해 고려해볼 점 — "지금 이런 상황이니, 이런 부분들을 한 번쯤 점검해보면 좋다"는
   식으로 2~4가지 정도, 구체적 종목이나 확정적 매수/매도 지시 없이 제시 (예: 환율 변동에 따른 환헤지 상품
   점검, 금리 국면에 따른 예금·채권 비중 재점검, 분산투자 원칙 재확인 등 일반적으로 고려되는 방향)
6. 이번 주 행동 강령 (참고용 정리) — 위 1~5번 내용을 종합해서, "지금 국면을 한 문장으로 요약하면 이렇다"는
   형태로 2~3개의 짧은 문장을 제시. 예시 톤: "환율은 당분간 추가 상승(원화 약세) 압력이 우세해 보여, 신규
   외화 매입은 서두르기보다 분할로 접근하는 편에 무게가 실립니다.", "금리 역전이 이어지는 국면이라, 신규
   주식 비중 확대는 관망 쪽에 조금 더 무게를 두는 게 합리적일 수 있습니다." — 이렇게 데이터가 가리키는
   방향을 분명하게 짚되, 명령형이 아니라 "~수 있습니다/~무게가 실립니다/~합리적일 수 있습니다" 같은 어조를
   유지. 이 섹션 바로 아래에 "이건 확정적 지시가 아니라 이번 주 데이터를 바탕으로 한 참고용 정리입니다"라는
   문구를 짧게 덧붙일 것.

위 6개 항목을 모두 빠짐없이 포함해서 작성해주세요. 각 항목은 간결하게 쓰되, 중간에 끊기지 않도록 전체
분량을 조절해주세요.
"""
    msg = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=3800,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": prompt}],
    )
    return msg.content[0].text


def generate_daily_alert(data: dict, triggered_reasons: list) -> str:
    prompt = f"""오늘 아래 조건이 감지되어 속보를 발송합니다: {triggered_reasons}

관련 데이터 (JSON):
{json.dumps(data, ensure_ascii=False, indent=2)}

쉬운 말로 2~3문단으로 설명해주세요:
1. 무슨 일이 있었는지, 왜 이런 변동이 생겼을 가능성이 있는지 (배경)
2. 이런 상황에서 한 번쯤 점검해보면 좋을 점 1~2가지
3. 마지막 한두 문장으로 "오늘 상황을 한 줄로 요약하면 이렇다"는 식의 짧은 정리를 덧붙일 것. 명령형이 아니라
   "~수 있습니다/~무게가 실립니다" 같은 어조로, 데이터가 가리키는 방향을 분명하게 짚어줄 것. 이건 확정적
   지시가 아니라 참고용 정리라는 점도 짧게 덧붙일 것.

문장이 중간에 끊기지 않도록 분량을 조절해서 완결된 형태로 작성해주세요.
"""
    msg = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=1500,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": prompt}],
    )
    return msg.content[0].text
